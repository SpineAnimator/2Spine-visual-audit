#!/usr/bin/env python3
"""Audit *official Spine Editor PNG exports*; never fabricate animation frames.

This script does not render art. It validates evidence generated by licensed
Spine 4.3.26, builds a visual contact sheet, and leaves artistic approval pending.
"""
import argparse
import hashlib
import json
from pathlib import Path
import math
from PIL import Image, ImageChops, ImageDraw, ImageOps, ImageStat
try:
    from .editor_source_color_guard import compare_native_setup
except ImportError:
    from editor_source_color_guard import compare_native_setup

SOURCE_SHA = "7adee866547a3b3cc9838b655cf70865980c5dba00313373cbf903fed776c7b2"
CLIPS = ("shoot_up_01", "shoot_up_02")


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def require(value, message):
    if not value:
        raise ValueError(message)


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def safe_frame_path(editor_dir, relative, clip):
    require(isinstance(relative, str), "Invalid frame path type")
    root = (editor_dir / "screenshots" / clip).resolve()
    candidate = (editor_dir / relative).resolve()
    require(candidate.is_relative_to(root) and candidate.suffix.lower() == ".png",
            "Frame path escapes its assigned clip directory")
    require(candidate.is_file() and not candidate.is_symlink(), "Official PNG frame missing")
    return candidate


def review_montage(original, sample_frames, output):
    # Audit contact sheet only; never changes source artwork or generates motion.
    tile_w, tile_h = 250, 210
    sheet = Image.new("RGB", (6 * tile_w, 3 * tile_h), "#292c36")
    draw = ImageDraw.Draw(sheet)
    for row, clip in enumerate(CLIPS):
        # The passed list is five sampled paths per clip, not synthetic frames.
        images = [("Source PSD", original)] + [
            (f"{i * 25}%", frame) for i, frame in enumerate(sample_frames[clip])
        ]
        for col, (label, path) in enumerate(images):
            with Image.open(path) as source:
                rgba = source.convert("RGBA")
                rgba.thumbnail((tile_w - 14, tile_h - 35), Image.Resampling.LANCZOS)
                back = Image.new("RGBA", rgba.size, "#333844")
                back.alpha_composite(rgba)
                rgb = back.convert("RGB")
            x = col * tile_w + (tile_w - rgb.width) // 2
            y = row * tile_h + 30 + (tile_h - 35 - rgb.height) // 2
            sheet.paste(rgb, (x, y))
            draw.text((col * tile_w + 8, row * tile_h + 9),
                      clip + " " + label if col else label, fill="white")
    # Last row explains the limits of the evidence, rather than displaying a fake pass.
    draw.text((12, 2 * tile_h + 12),
              "Rendered PNGs are proof of Editor output, not proof of artistic approval.",
              fill="white")
    output.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(output)


def reject_frozen_interior_frames(digests, clip, *, max_consecutive=7, margin=3):
    """Reject long byte-identical interior Editor PNG holds, not source stills.

    Original setup/settle poses may legitimately remain still at both ends.
    Only repeats fully inside the actual animation are suspicious here.
    """
    start = 0
    for end in range(1, len(digests) + 1):
        if end < len(digests) and digests[start] == digests[end]:
            continue
        length = end - start
        if length > max_consecutive and start >= margin and end <= len(digests) - margin:
            raise ValueError(
                f"{clip}: frozen interior Editor PNGs {start}-{end - 1} "
                f"({length} identical frames). No artistic approval."
            )
        start = end


# These are *real Spine Editor PNG* motion measurements. This does not
# generate a single animation frame or alter the user's PSD artwork.
def official_motion_envelope(frames, size=(160, 120)):
    """Mean per-frame RGB change versus this clip's own setup screenshot."""
    colors = []
    for name in frames:
        with Image.open(name) as image:
            source = image.convert("RGBA").resize(size, Image.Resampling.BILINEAR)
        backdrop = Image.new("RGBA", size, "#343741")
        backdrop.alpha_composite(source)
        colors.append(backdrop.convert("RGB"))
    reference = colors[0]
    return [sum(ImageStat.Stat(ImageChops.difference(reference, frame)).mean) / 3
            for frame in colors]


def motion_envelope_similarity(left, right):
    """Pearson r of time-normalized actual Editor image-motion intensities."""
    require(len(left) > 1 and len(right) > 1, "Missing real clip motion data")
    n = max(len(left), len(right), 25)
    def at(values, frame):
        x = frame * (len(values) - 1) / (n - 1)
        low = int(x)
        high = min(low + 1, len(values) - 1)
        return values[low] + (values[high] - values[low]) * (x - low)
    a = [at(left, i) for i in range(n)]
    b = [at(right, i) for i in range(n)]
    ma, mb = sum(a) / n, sum(b) / n
    centered_a = [v - ma for v in a]
    centered_b = [v - mb for v in b]
    ea = sum(v * v for v in centered_a)
    eb = sum(v * v for v in centered_b)
    if ea < 1e-12 or eb < 1e-12:
        return 1.0 if ea < 1e-12 and eb < 1e-12 else 0.0
    return sum(v * w for v, w in zip(centered_a, centered_b)) / ((ea * eb) ** .5)



def rendered_action_distinctness(left_frames, right_frames, size=(160, 120)):
    """Compare official Editor PNGs using pose-relative, energy-normalized pixels.

    Same image-motion trajectories with different timing/scale are not new art.
    This function is a suspicious-similarity flag, NOT art approval.
    """
    require(len(left_frames) >= 24 and len(right_frames) >= 24,
            "Complete official Editor sequences required for distinctness")
    def render(paths):
        output = []
        for name in paths:
            with Image.open(name) as im:
                require(im.format == "PNG", "Non-PNG official Editor frame")
                picture = im.convert("RGBA").resize(size, Image.Resampling.BILINEAR)
            bg = Image.new("RGBA", size, "#343741")
            bg.alpha_composite(picture)
            output.append(bg.convert("RGB").tobytes())
        return output
    left, right = render(left_frames), render(right_frames)
    n = max(len(left), len(right))
    def sample(frames, i):
        return frames[round(i * (len(frames) - 1) / (n - 1))]
    left_zero, right_zero = left[0], right[0]
    ea = eb = dot = 0
    abs_a = abs_b = 0
    for frame_index in range(n):
        for a, b, a0, b0 in zip(sample(left, frame_index), sample(right, frame_index),
                                left_zero, right_zero):
            da, db = a - a0, b - b0
            ea += da * da
            eb += db * db
            dot += da * db
            abs_a += abs(da)
            abs_b += abs(db)
    require(ea > 0 and eb > 0, "Cannot certify distinctness from static clip")
    scale = math.sqrt(ea / eb)
    residual_sum = 0.
    for frame_index in range(n):
        for a, b, a0, b0 in zip(sample(left, frame_index), sample(right, frame_index),
                                left_zero, right_zero):
            residual_sum += abs((a - a0) - scale * (b - b0))
    cosine = max(-1., min(1., dot / math.sqrt(ea * eb)))
    residual = 2 * residual_sum / (abs_a + scale * abs_b)
    return {
        "sampled_official_frames": n,
        "setup_subtracted_motion_cosine": round(cosine, 6),
        "amplitude_normalized_action_residual": round(residual, 6),
        "method": "actual rendered RGB motion relative to each clip setup; energy normalized",
    }


def audit(archive, editor_dir, fidelity_path, original_png, output_dir):
    archive, editor_dir = Path(archive), Path(editor_dir)
    output_dir = Path(output_dir)
    receipt = read_json(editor_dir / "editor-roundtrip-report.json")
    fidelity = read_json(fidelity_path)
    require(receipt.get("editor_import_verified") is True, "Real Editor import unverified")
    require(receipt.get("native_spine_project_verified") is True, "Native Editor project unverified")
    require(receipt.get("spine_render_nonblank_frames_verified") is True,
            "Official Editor PNG render unverified")
    require(receipt.get("roundtrip_spine_version") == "4.3.26",
            "Editor roundtrip version mismatch")
    require(receipt.get("source_archive_sha256") == digest(archive),
            "Source ZIP no longer matches real Editor roundtrip")
    native = editor_dir / "clgb71-editor-4.3.26.spine"
    require(native.is_file() and digest(native) == receipt.get("native_project_sha256"),
            "Native .spine is missing or changed")
    require(fidelity.get("source_sha256") == SOURCE_SHA, "Fidelity report uses wrong source")
    require(fidelity.get("raster_layer_pixels_identical") is True and
            fidelity.get("draw_order_identical") is True and
            fidelity.get("verified_layer_count") == 38,
            "Original PSD pixel / draw order fidelity is unverified")
    require(fidelity.get("source_composite_alpha_proxy_guard_passed") is True,
            "Source composite preflight failed")
    require(Path(original_png).is_file(), "Missing real PSD composite reference")
    listed = receipt.get("official_rendered_frames")
    require(isinstance(listed, list) and len(listed) >= 8,
            "Official Editor frames not listed")
    per_clip = {}
    chosen = {}
    all_paths = set()
    motion_envelopes = {}
    actual_render_paths = {}
    for clip in CLIPS:
        matches = [name for name in listed
                   if isinstance(name, str) and Path(name).parts[:2] == ("screenshots", clip)]
        require(len(matches) >= 4, "Too few real Editor-rendered frames: " + clip)
        records = []
        for name in matches:
            path = safe_frame_path(editor_dir, name, clip)
            require(str(path) not in all_paths, "Duplicate frame path")
            all_paths.add(str(path))
            with Image.open(path) as im:
                require(im.format == "PNG", "Editor frame is not PNG")
                im.load()
                require(2 <= im.width <= 8192 and 2 <= im.height <= 8192,
                        "Invalid rendered frame dimensions")
                rgba = im.convert("RGBA")
                require(rgba.getchannel("A").getbbox() is not None,
                        "Blank transparent official render")
                bbox = rgba.getchannel("A").getbbox()
                require(bbox[2] > bbox[0] and bbox[3] > bbox[1],
                        "Invalid alpha bounds")
            records.append({"path": name, "sha256": digest(path),
                            "size": [im.width, im.height]})
        unique = len({r["sha256"] for r in records})
        require(unique > 1, "Only static/identical frames in " + clip)
        reject_frozen_interior_frames([r["sha256"] for r in records], clip)
        # Inspect every genuine Editor frame, not merely beginning/middle/end.
        actual_render_paths[clip] = [safe_frame_path(editor_dir, name, clip) for name in matches]
        motion_envelopes[clip] = official_motion_envelope(actual_render_paths[clip])
        per_clip[clip] = {
            "frame_count": len(records), "distinct_frame_files": unique,
            "frame_evidence": records
        }
        selected = [matches[round(i * (len(matches) - 1) / 4)] for i in range(5)]
        chosen[clip] = [safe_frame_path(editor_dir, name, clip) for name in selected]
    a = [r["sha256"] for r in per_clip[CLIPS[0]]["frame_evidence"]]
    b = [r["sha256"] for r in per_clip[CLIPS[1]]["frame_evidence"]]
    exact_duplicate = a == b
    near_duplicate_threshold = 0.985
    # This classifier needs a full real render; a four-frame unit fixture or
    # a partial screenshot bundle must never be mistaken for holistic QA.
    full_evidence = all(per_clip[clip]["frame_count"] >= 24 for clip in CLIPS)
    motion_r = motion_envelope_similarity(
        motion_envelopes[CLIPS[0]], motion_envelopes[CLIPS[1]]) if full_evidence else None
    spatial = rendered_action_distinctness(
        actual_render_paths[CLIPS[0]], actual_render_paths[CLIPS[1]]) if full_evidence else None
    spatial_near_duplicate = (
        spatial is not None and motion_r is not None and motion_r >= .95 and
        spatial["setup_subtracted_motion_cosine"] >= .90 and
        spatial["amplitude_normalized_action_residual"] <= .32
    )
    potential_duplicate = exact_duplicate or (
        motion_r is not None and motion_r >= near_duplicate_threshold) or spatial_near_duplicate
    output_dir.mkdir(parents=True, exist_ok=True)
    sheet = output_dir / "artistic-review-contact-sheet.png"
    review_montage(Path(original_png), chosen, sheet)
    # This is true licensed Editor screenshot vs PSD composite, not only
    # comparison between two calculated PSD raster composites.
    approx_path = Path(fidelity_path).parent / "exported-layer-composite-approx.png"
    registered = {}
    if approx_path.is_file():
        for clip in CLIPS:
            registered[clip] = {
                "first": compare_native_setup(original_png, approx_path, chosen[clip][0]),
                "last": compare_native_setup(original_png, approx_path, chosen[clip][-1])
            }
    color_status = ("REVIEW_REQUIRED_PSD_COLOR" if any(
        not result[side]["photoshop_compositing_equivalent"]
        for result in registered.values() for side in ("first","last"))
        else "NUMERICALLY_CLOSE_NOT_ARTISTIC_APPROVED" if registered
        else "UNAVAILABLE_MISSING_APPROXIMATION")
    report = {
        "schema": "2spine.real-editor-art-audit.v1",
        "source_psd_sha256": SOURCE_SHA,
        "source_archive_sha256": digest(archive),
        "native_project_sha256": digest(native),
        "official_editor_version": "4.3.26",
        "editor_import_verified": True,
        "official_frame_evidence_verified": True,
        "source_raster_pixels_verified": True,
        "source_draw_order_verified": True,
        "clip_evidence": per_clip,
        "suspected_duplicate_render_sequences": potential_duplicate,
        "real_editor_motion_envelope_pearson_r":
            round(motion_r, 6) if motion_r is not None else None,
        "near_duplicate_motion_threshold": near_duplicate_threshold,
        "cross_clip_rendered_action": spatial,
        "same_action_rhythm_and_pixels": bool(spatial_near_duplicate),
        "cross_clip_review_thresholds": {
            "minimum_motion_envelope_r": .95,
            "minimum_motion_cosine": .90,
            "maximum_normalized_residual": .32
        },
        "near_duplicate_evidence_only": True,
        "native_setup_psd_color_status": color_status,
        "native_setup_psd_color_registration": registered,
        "native_setup_psd_color_approval": False,
        "review_sheet_sha256": digest(sheet),
        "visual_review_status": "rejected_near_duplicate_choreography"
            if potential_duplicate else "pending_human_review",
        "artistic_quality_approved": False,
        "release_ready": False,
        "review_criteria": [
            "source silhouette and setup pose fidelity",
            "readable anticipation, accent, hold and settle",
            "arm/weapon contact throughout movement",
            "natural mesh deformation without broken triangles",
            "distinct choreography and timing between clips",
            "no unwanted flips, layer disappearances or fake 360-degree turns"
        ],
        "notes": "Passing static checks and licensed Editor PNG export does not certify aesthetics."
    }
    (output_dir / "artistic-evidence-report.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    template = {
        "source_archive_sha256": report["source_archive_sha256"],
        "native_project_sha256": report["native_project_sha256"],
        "review_sheet_sha256": report["review_sheet_sha256"],
        "review_status": "pending", "reviewer": None, "reviewed_at": None,
        "scores_1_to_5": {criterion: None for criterion in report["review_criteria"]},
        "comments": ""
    }
    (output_dir / "human-art-review-template.json").write_text(
        json.dumps(template, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return report


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--archive", type=Path, required=True)
    p.add_argument("--editor-dir", type=Path, required=True)
    p.add_argument("--fidelity-report", type=Path, required=True)
    p.add_argument("--source-composite", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    args = p.parse_args()
    result = audit(args.archive, args.editor_dir, args.fidelity_report,
                   args.source_composite, args.output)
    print("SPINE_REAL_RENDER_EVIDENCE_VERIFIED", json.dumps({
        "archive": result["source_archive_sha256"],
        "clips": {k: v["frame_count"] for k, v in result["clip_evidence"].items()},
        "artistic_status": result["visual_review_status"]
    }))


if __name__ == "__main__":
    main()
